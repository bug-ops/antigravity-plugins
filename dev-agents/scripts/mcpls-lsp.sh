#!/usr/bin/env bash
# Starts mcpls (MCP-to-LSP bridge) over stdio with a generated config pointing at this plugin's
# LSP launcher scripts for Rust, TypeScript/JavaScript, Luau, and Lua.
# stdout carries strictly MCP JSON-RPC traffic; diagnostics go to stderr.
set -euo pipefail

script_dir=$(cd "$(dirname "$0")" && pwd -P)
plugin_root=${PLUGIN_ROOT:-$(dirname "$script_dir")}
data_dir=${PLUGIN_DATA:-${XDG_CACHE_HOME:-$HOME/.cache}/dev-agents}

if ! command -v mcpls >/dev/null 2>&1; then
  echo "dev-agents: mcpls not found on PATH; install with: cargo install mcpls (or see https://github.com/bug-ops/mcpls)" >&2
  exit 1
fi

mkdir -p "$data_dir"
cfg="$data_dir/mcpls.toml"
tmp="$cfg.tmp.$$"

# Escape backslashes and double quotes for TOML basic strings.
toml_escape() {
  local s=$1
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  printf '%s' "$s"
}

rust_script=$(toml_escape "$plugin_root/scripts/rust-lsp.sh")
lua_script=$(toml_escape "$plugin_root/scripts/lua-lsp.sh")

cat >"$tmp" <<EOF
# Generated by dev-agents/scripts/mcpls-lsp.sh — do not edit manually.
# Override by setting MCPLS_CONFIG or placing a trusted mcpls.toml in your workspace.

[workspace]
roots = []
language_extensions = [
  { extensions = ["rs"], language_id = "rust" },
  { extensions = ["ts", "tsx", "mts", "cts"], language_id = "typescript" },
  { extensions = ["js", "jsx", "mjs", "cjs"], language_id = "javascript" },
  { extensions = ["luau"], language_id = "luau" },
  { extensions = ["lua"], language_id = "lua" },
]

[[lsp_servers]]
name = "rust-analyzer"
language_id = "rust"
command = "bash"
args = ["$rust_script"]
file_patterns = ["**/*.rs"]
timeout_seconds = 60
request_timeout_seconds = 30
heuristics = { project_markers = ["Cargo.toml"] }

[lsp_servers.initialization_options.cargo]
features = "all"

[lsp_servers.initialization_options.cargo.buildScripts]
enable = true

[lsp_servers.initialization_options.check]
command = "clippy"

[lsp_servers.initialization_options.diagnostics]
enable = true

[lsp_servers.initialization_options.diagnostics.experimental]
enable = true

[lsp_servers.initialization_options.inlayHints.typeHints]
enable = true

[lsp_servers.initialization_options.inlayHints.parameterHints]
enable = true

[lsp_servers.initialization_options.inlayHints.chainingHints]
enable = true

[lsp_servers.initialization_options.procMacro]
enable = true

[[lsp_servers]]
name = "typescript-language-server"
language_id = "typescript"
command = "typescript-language-server"
args = ["--stdio"]
file_patterns = ["**/*.ts", "**/*.tsx", "**/*.mts", "**/*.cts", "**/*.js", "**/*.jsx", "**/*.mjs", "**/*.cjs"]
timeout_seconds = 30
request_timeout_seconds = 30
heuristics = { project_markers = ["tsconfig.json", "package.json"] }

[[lsp_servers]]
name = "luau-lsp"
language_id = "luau"
command = "bash"
args = ["$lua_script", "luau"]
file_patterns = ["**/*.luau"]
timeout_seconds = 30
request_timeout_seconds = 30
heuristics = { project_markers = ["default.project.json", "wally.toml", "pesde.toml", ".luaurc", ".config.luau"] }

[[lsp_servers]]
name = "lua-language-server"
language_id = "lua"
command = "bash"
args = ["$lua_script", "lua"]
file_patterns = ["**/*.lua"]
timeout_seconds = 30
request_timeout_seconds = 30
heuristics = { project_markers = [".luarc.json", ".busted", "stylua.toml", "selene.toml"] }
EOF

mv "$tmp" "$cfg"

if [[ ${DEV_AGENTS_MCPLS_DRY_RUN:-0} == 1 ]]; then
  echo "$cfg"
  exit 0
fi

exec mcpls --config "$cfg" "$@"
